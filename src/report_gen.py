from fpdf import FPDF


def safe_text(value, max_len=120):
    text = str(value)
    text = text.replace("\n", " ").replace("\r", " ")
    text = " ".join(text.split())
    if len(text) > max_len:
        text = text[:max_len] + "..."
    return text


def generate_medical_pdf(patient_name, risk_score, symptoms_summary):
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    left_margin = 10
    printable_width = 190

    pdf.set_font("Arial", "B", 16)
    pdf.set_x(left_margin)
    pdf.cell(printable_width, 10, "Lupus Risk Assessment Report", new_x="LMARGIN", new_y="NEXT", align="C")

    pdf.ln(8)

    pdf.set_font("Arial", "", 12)
    pdf.set_x(left_margin)
    pdf.cell(printable_width, 8, f"Patient Name: {safe_text(patient_name)}", new_x="LMARGIN", new_y="NEXT")

    pdf.set_x(left_margin)
    pdf.cell(printable_width, 8, f"Estimated Lupus Probability: {float(risk_score):.2f}%", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)

    pdf.set_font("Arial", "B", 13)
    pdf.set_x(left_margin)
    pdf.cell(printable_width, 8, "Clinical Summary:", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(2)

    pdf.set_font("Arial", "", 11)
    for key, value in symptoms_summary.items():
        line = f"{safe_text(key, 50)}: {safe_text(value, 100)}"
        pdf.set_x(left_margin)
        pdf.multi_cell(printable_width, 8, line)

    pdf.ln(4)

    pdf.set_font("Arial", "I", 10)
    disclaimer = (
        "This report is generated by a hybrid AI-based decision support system. "
        "It is intended for screening support and should not replace clinical judgment."
    )
    pdf.set_x(left_margin)
    pdf.multi_cell(printable_width, 8, disclaimer)

    output_data = pdf.output(dest="S")

    if isinstance(output_data, bytearray):
        return bytes(output_data)
    if isinstance(output_data, bytes):
        return output_data
    return output_data.encode("latin-1")